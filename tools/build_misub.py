"""Build the MiSub native template: python -B tools/build_misub.py [--refresh-ai]."""

import argparse
from pathlib import Path
from urllib.request import Request, urlopen


ROOT = Path(__file__).resolve().parents[1]
RAW_BASE = "https://raw.githubusercontent.com/FoLeaf/clash_rules_self/main/"
AI_SOURCE = "https://raw.githubusercontent.com/VPSDance/ai-proxy-rules/main/rules/quantumult-x/global.list"
AI = "\U0001f916 AI"


def refresh_ai():
    request = Request(AI_SOURCE, headers={"User-Agent": "clash-rules-self"})
    with urlopen(request, timeout=30) as response:
        source = response.read().decode("utf-8-sig")
    aliases = {"HOST": "DOMAIN", "HOST-SUFFIX": "DOMAIN-SUFFIX",
               "HOST-KEYWORD": "DOMAIN-KEYWORD", "IP6-CIDR": "IP-CIDR6"}
    rules = []
    for line in source.splitlines():
        if not line.strip() or line.lstrip().startswith(("#", ";", "//")):
            continue
        fields = [field.strip() for field in line.split(",")]
        kind = aliases.get(fields[0].upper(), fields[0].upper())
        if kind not in ("DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD", "IP-CIDR", "IP-CIDR6", "IP-ASN"):
            raise ValueError("Unexpected upstream rule type: " + kind)
        rule = kind + "," + fields[1]
        if fields[-1] == "no-resolve":
            rule += ",no-resolve"
        if rule not in rules:
            rules.append(rule)
    if not rules:
        raise ValueError("Empty AI source")
    header = ("# Overseas AI destination snapshot; no whole-process rules.\n"
              "# Source: " + AI_SOURCE + "\n"
              "# Refresh: python -B tools/build_misub.py --refresh-ai\n")
    (ROOT / "rules/overseas-ai.list").write_text(header + "\n".join(rules) + "\n",
                                              encoding="utf-8", newline="")


def build(text):
    # Native rule providers retain flags inside their payloads. MiSub currently
    # drops inline extras such as no-resolve and cannot parse inline AND rules.
    start = text.index("; BEGIN OPENAI AI OVERRIDES")
    end = text.index("; END OPENAI AI OVERRIDES", start) + len("; END OPENAI AI OVERRIDES")
    text = text[:start] + f"ruleset={AI},{RAW_BASE}rules/openai-ai.list" + text[end:]
    text = text.replace("quanx:" + AI_SOURCE, RAW_BASE + "rules/overseas-ai.list")
    text = text.replace("[]GEOIP,CN,no-resolve", RAW_BASE + "rules/cn-ip-fallback.list")
    output = ["[custom]", "; MiSub native engine; no client JavaScript override required.",
              "; Generated by tools/build_misub.py. Edit the canonical INI and rebuild.",
              "; Publish this INI AND the rules/ files before importing.",
              "; Set MiSub UDP forwarding ON and install configs/misub-dns.yaml in its DNS editor.",
              "; Each proxy rule is followed by the same predicate targeting REJECT.",
              "; TCP / supported UDP take the first rule; unsupported UDP cannot reach DIRECT."]
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith((";", "#")) or line == "[custom]":
            continue
        if line.startswith("ruleset="):
            policy, source = line[len("ruleset="):].split(",", 1)
            output.append(line)
            if policy not in ("DIRECT", "REJECT", "REJECT-DROP"):
                output.append("ruleset=REJECT," + source)
        elif line.startswith("custom_proxy_group="):
            # MiSub treats a literal ^name$ as a member, not a regex. Explicit
            # members preserve preferred-node order and are pruned if missing.
            fields = line.split("`")
            output.append("`".join("[]" + value[1:-1] if value.startswith("^") and value.endswith("$")
                                   else value for value in fields))
        else:
            output.append(line)
    return "\n".join(output) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-ai", action="store_true")
    args = parser.parse_args()
    if args.refresh_ai:
        refresh_ai()
    if not (ROOT / "rules/overseas-ai.list").exists():
        parser.error("Missing AI snapshot; run once with --refresh-ai")
    result = build((ROOT / "acl4ssr-ai-chain-v2.ini").read_text(encoding="utf-8-sig"))
    (ROOT / "acl4ssr-ai-chain-misub.ini").write_text(result, encoding="utf-8", newline="")
    print(f"Built MiSub template: {len(result)} characters (128 KiB editor limit)")
